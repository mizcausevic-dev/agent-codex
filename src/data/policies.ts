export function findPolicy(id: string): Policy | undefined {
  return policies.find((p) => p.id === id);
}

export function findPack(id: string): PolicyPack | undefined {
  return policyPacks.find((p) => p.id === id);
}

export function policiesInPack(packId: string): Policy[] {
  const pack = findPack(packId);
  if (!pack) return [];
  return pack.policyIds
    .map((id) => findPolicy(id))
    .filter((p): p is Policy => p !== undefined);
}
